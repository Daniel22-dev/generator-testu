#!/usr/bin/env node
// GIT 7.1.90 — regresní kontrakt produktivních odpovědí (bod 10/11 auditu 4. 10. 2026).
// Čistě deterministické: stejná factory jako v instant testu i verifieru (createSharedScoringApi).
import fs from 'node:fs';
import vm from 'node:vm';
const ctx = vm.createContext({});
vm.runInContext(fs.readFileSync('src/js/13b-secure-shared-scoring.js', 'utf8') + '\n;globalThis.__api=createSharedScoringDiagnosticApi;', ctx);
const mk = ctx.__api;
let failed = 0, passed = 0;
const check = (got, want, msg) => { if (Math.abs(got - want) < 1e-9) { passed++; } else { failed++; console.error(`FAIL ${msg}: očekáváno ${want}, dostal ${got}`); } };
const api = mk({ fuzzyMode: 'off' });
const EC = (given, item) => api.correctionScore(given, item, 'error correction');
const ecFull = { sentence: 'He have been there before.', correction: 'He has been there before.', alt_answers: [] };
check(EC('He has been there before.', ecFull), 1, 'EC celá věta');
check(EC('has', ecFull), 1, 'EC jen opravený tvar');
check(EC('has been', ecFull), 0, 'EC úsek s kontextem se neuzná (jen přesný změněný úsek)');
check(EC('He has', ecFull), 0, 'EC úsek s levým kontextem se neuzná');
check(EC('  HAS  ', ecFull), 1, 'EC velikost písmen a mezery');
check(EC('he has been there before', ecFull), 1, 'EC bez interpunkce');
check(EC('He has  been there before!', ecFull), 1, 'EC jiná koncová interpunkce');
check(EC('have -> has', ecFull), 0, 'EC zápis chyba -> oprava se neuzná (není deklarován)');
check(EC('have → has', ecFull), 0, 'EC zápis chyba → oprava se neuzná');
check(EC('He\u2019s tired.', { sentence: 'He are tired.', correction: "He's tired.", alt_answers: [] }), 1, 'EC typografický apostrof');
check(EC('has nonsense whatever', ecFull), 0, 'EC správné slovo uvnitř nesmyslu');
check(EC('ha', ecFull), 0, 'EC jen část slova');
check(EC('have', ecFull), 0, 'EC ponechaná chyba');
check(EC('He have been there before.', ecFull), 0, 'EC opsaná chybná věta');
check(EC('been there before', ecFull), 0, 'EC správný úsek bez opravy');
check(EC('had', ecFull), 0, 'EC jiný tvar');
check(EC('He has been there before yesterday.', ecFull), 0, 'EC navíc text měnící větu');
check(EC('has has', ecFull), 0, 'EC zdvojení');
check(EC('', ecFull), 0, 'EC prázdná odpověď');
const ecDel = { sentence: 'He is more taller than me.', correction: 'He is taller than me.', alt_answers: [] };
check(EC('He is taller than me.', ecDel), 1, 'EC smazání: celá věta');
check(EC('is taller', ecDel), 0, 'EC smazání: jen celá věta');
check(EC('taller', ecDel), 0, 'EC smazání: úsek bez důkazu smazání');
check(EC('more taller', ecDel), 0, 'EC smazání: ponechaná chyba');
const ecIns = { sentence: 'She is good teacher.', correction: 'She is a good teacher.', alt_answers: [] };
check(EC('a', ecIns), 1, 'EC vložení: vložené slovo');
check(EC('a good teacher', ecIns), 0, 'EC vložení: úsek s kontextem se neuzná');
check(EC('good teacher', ecIns), 0, 'EC vložení: úsek bez vloženého slova');
const ecFrag = { sentence: 'They was late yesterday.', correction: 'were', alt_answers: [] };
check(EC('were', ecFrag), 1, 'EC klíč jen tvar: tvar');
check(EC('They were late yesterday.', ecFrag), 0, 'EC klíč jen tvar: celá věta se bez klíče neuzná (bezpečná varianta)');
check(EC('They were late yesterday.', { sentence: 'They was late yesterday.', correction: 'were', alt_answers: ['They were late yesterday.'] }), 1, 'EC klíč jen tvar + explicitní alternativa celé věty');
const ecAlt = { sentence: 'His face was wrinkle.', correction: 'His face was wrinkled.', alt_answers: ['His face was wrinkly.'] };
check(EC('wrinkled', ecAlt), 1, 'EC alternativa 1 (tvar)');
check(EC('wrinkly', ecAlt), 1, 'EC alternativa 2 (tvar z alt_answers)');
check(EC('wrinkles', ecAlt), 0, 'EC nepovolený tvar');
check(EC('has', { sentence: 'He have been there before.', answer: 'He has been there before.' }), 1, 'EC klíč v poli answer');
check(EC('recieve', { sentence: 'I didnt receives it.', correction: 'I didnt receive it.' }), 0, 'EC překlep bez tolerance');
check(mk({ fuzzyMode: 'mild' }).correctionScore('receve', { sentence: 'I didnt receives it.', correction: 'I didnt receive it.' }, 'error correction'), 0.5, 'EC překlep při mírné toleranci (gramaticky citlivý typ 0,5)');
const et = { sentence: 'She go to the the shop.', tokens: ['She', 'go', 'to', 'the', 'the', 'shop.'], error_token_index: 1, error_type: 'verb form', error_type_options: ['verb form', 'spelling'], correction: 'goes', alt_answers: [] };
const ET = v => api.errorTaggingScore(v, et, 3, 'error-tagging');
check(ET({ token: 1, etype: 'verb form', corr: 'goes' }), 3, 'ET vše správně (tvar)');
check(ET({ token: 1, etype: 'verb form', corr: 'She goes to the the shop.' }), 3, 'ET oprava celou větou');
check(ET({ token: 1, etype: 'verb form', corr: 'goes nonsense' }), 2, 'ET nesmyslná oprava = jen token a typ');
check(ET({ token: 3, etype: 'spelling', corr: 'gone' }), 0, 'ET vše špatně');
const WF = (v, it) => api.gapTextScore(v, api.productiveText(it), [it.answer].concat(it.alt_answers || []), [it.base_word], 'word formation');
const wf = { sentence: 'Her ___ (decide) was final.', base_word: 'decide', answer: 'decision', alt_answers: [] };
check(WF('decision', wf), 1, 'WF tvar');
check(WF('Her decision was final.', wf), 1, 'WF celá věta (nápověda v závorce odstraněna)');
check(WF('decide', wf), 0, 'WF výchozí slovo');
check(WF('Her decide was final.', wf), 0, 'WF celá věta se špatným tvarem');
check(WF('decision was', wf), 0, 'WF tvar s částí věty');
const wfNoGap = { prompt: 'Form a noun from decide.', base_word: 'decide', answer: 'decision', alt_answers: [] };
check(WF('decision', wfNoGap), 1, 'WF bez mezery: tvar');
const ST = (v, it) => api.gapTextScore(v, api.productiveText(it), [it.answer].concat(it.alt_answers || []), [it.keyword], 'sentence transformation');
const kwt = { prompt: 'It is a pity I cannot swim. (WISH)\nI ___ swim.', keyword: 'wish', answer: 'wish I could', alt_answers: [] };
check(ST('wish I could', kwt), 1, 'KWT doplnění');
check(ST('I wish I could swim.', kwt), 1, 'KWT celá druhá věta');
check(ST('I could swim', kwt), 0, 'KWT bez klíčového slova');
check(ST('It is a pity I cannot swim.', kwt), 0, 'KWT opsaná výchozí věta');
const kwtFull = { prompt: 'He started working here two years ago. (FOR)\nHe ___ two years.', keyword: 'for', answer: 'He has been working here for two years.', alt_answers: [] };
check(ST('has been working here for', kwtFull), 1, 'KWT klíč jako celá věta: doplnění');
check(ST('He has been working here for two years.', kwtFull), 1, 'KWT klíč jako celá věta: věta');
check(ST('has working here for', kwtFull), 0, 'KWT chybné doplnění');
const st = { prompt: 'Rewrite in passive: They built the house.', answer: 'The house was built.', alt_answers: ['The house was built by them.'] };
check(ST('The house was built by them.', st), 1, 'ST bez mezery: celá věta (alternativa)');
check(ST('was built', st), 0, 'ST bez mezery: fragment se neuzná (transformace celé věty je cílem)');
check(ST('built', st), 0, 'ST bez mezery: jedno slovo');
check(api.textScore('I have got a dog.', 'I have a dog.', ['I have got a dog.'], 'translation'), 1, 'TR alternativa');
check(api.textScore('a dog', 'I have a dog.', [], 'translation'), 0, 'TR fragment se neuzná');
check(api.textScore('I like', 'I like tea.', [], 'word order'), 0, 'WO fragment se neuzná');
check(api.scoreBlanks(['is'], ['is a'], [], 1, 'fill-in-the-blank', true), 0, 'FIB správné slovo s textem navíc');
check(api.scoreBlanks(['is'], [' IS '], [], 1, 'fill-in-the-blank', true), 1, 'FIB velikost písmen a mezery');
check(api.transformationChainScore(['She does not go'], [{ instruction: 'Negative', answer: 'She does not go to school.' }], 1, 'transformation-chain'), 0, 'TRCH fragment se neuzná');
const fr = api.correctionAnswers(ecFull, 'error correction');
check(fr.length === 2 && fr[1] === 'has' ? 1 : 0, 1, 'odvozený opravený úsek pro zobrazení klíče');
console.log(`${failed ? 'FAIL' : 'PASS'} productive answer contract: ${passed} PASS / ${failed} FAIL`);
if (failed) process.exit(1);
